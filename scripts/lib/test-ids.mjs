/** يقصّ أو يُكمل إلى عشرة أرقام بالضبط. */
const pad10 = (s) => String(s).replace(/\D/g, '').padEnd(10, '0').slice(0, 10)

/** رقم سجل تجاري صالح: عشرة أرقام. */
export const crNumber = (prefix, seed) => pad10(`${prefix}${seed}`)

/** رقم موحّد صالح: عشرة أرقام تبدأ بـ 70. */
export const unifiedNumber = (seed) => pad10(`70${String(seed).replace(/\D/g, '')}`)

export { pad10 }
